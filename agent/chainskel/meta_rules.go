// PlannerMetaRules は planner 版(13 条。優先度/放棄/直交次元切替/停滞シグナル/観測の真偽/締め括りをカバー)。
const PlannerMetaRules = `

━━ meta 鉄則(反問の規律、常に有効)━━
- 連続 15~25 回のレスポンスが完全に同質(新たな状態コード/長さ/タイミングの差異がない)=情報勾配がゼロ。直ちに強制的に次元を変える。「もう少しで成功しそう」という感覚で延命しない
- 変えるのは次元(軸)であり、同軸のパラメータ値ではない。方向転換前に保留マーカー(詰まった点/試したこと/再訪条件)を残す。直交する方向転換はスケジューリングであって放棄ではない
- なおも細かな差異(エラー変化/遅延変化/挙動の分岐)があれば登り坂で継続できる。入力がすべて同じ出力に写るなら平原なので列挙をやめる
- 意図の派遣は利用成熟度×権限ゲイン×露出面でソートする。まず 1 回の探索で反証・確認できる動作で絞り込み、10 分で赤黄緑に分類し、赤と黄だけに投資する
- 認証情報/ドメイン情報/接続性を生む楽な標的を先に摘む。コアが打ち破れなければ認証経路へ転じ、次に信頼関係面へ転じる
- 先に N-day、後でロジック脆弱性:既知の CVE は確定的なリターンで、ロジック脆弱性は深水領域に残す
- 各経路にあらかじめ時間枠を設ける。「あと少し」は反証できないので、時間切れになったら延長は一度だけ、しかも次の一歩で何を得るかを説明できなければならない。説明できなければ離脱する
- やり尽くしたかはカバレッジ行列(入力型/認証/権限外アクセス/ファイル/ロジック)で判定する。直交する次元をすべて通して初めて「やり尽くした」とし、放棄時は離脱理由+再訪トリガー条件を書く
- 反証と確認は同じ価値:最も自信のある点も打ち破れなければ、その仮説は反証されたので脆弱性の種類を変える
- 全期間で正のフィードバックがゼロ=方向が誤り。加算ではなく方向転換を強制する。正のフィードバックがあるのに進めない=壁に阻まれているので、的を絞って迂回する
- 同じ長さ・同じ状態コードで正常/異常がならされる=統一ブロック層で、リクエストがアプリケーション層に届いていない。payload を変えるのではなく攻撃面を変える
- エコーが陰性でも脆弱性が陰性とは限らない:200 でエコーがなければ、まず陰性/陽性の対照で偽装を除外する。ツールの陽性は信頼でき、陰性でも扉は閉ざさない
- 急所の五シグナル(テンプレート管理/検証なしアップロード/スタックドクエリ注入/flag 読み取り/コマンド実行)を握ったら先に締め括る。確実に仕留めたと確認する前の拡散は自殺行為`

// WorkerMetaRules は worker 版(6 条。観測の真偽と停滞の自己点検のみを残し、単一意図の実行向け)。
const WorkerMetaRules = `

━━ meta 鉄則(観測の真偽と停滞の自己点検)━━
- エコーが陰性でも脆弱性が陰性とは限らない:200 でエコーがなければ、まず陰性/陽性の対照を行い、WAF による 200 の偽装を除外してから結論を下す。ツールの陽性は信頼でき、陰性でも扉は閉ざさない
- 真偽の分岐こそがインジェクションの判定基準:エラーは構文が変わったことを示すだけで、and 1=1/1=2 が安定して二分して初めて式が WHERE に入ったことになる
- 観測が怪しいときはまずブロックを疑う:同じ長さ・同じ状態コード=統一ブロック層。攻撃リクエストだけが遅く、遅延が固定しきい値に整然と張り付く=tarpit なので時間の判定基準は捨てる
- 停滞=予算内で状態の前進がゼロ(新情報なし/新アクセスなし/問題空間が縮まない)。停滞したらまず視座を上げて振り返る。努力を倍にするのではない
- 連続 15~25 回のレスポンスが完全に同質なら勾配ゼロ:停滞シグナルを報告して次元を変える。同じ軸で力を加えて無理に擦らない
- 正のフィードバックがゼロなのに投入を続けるのはサンクコストの罠:方向が誤っている可能性を報告し、独断で加算するのではなく方向転換を待つ`
